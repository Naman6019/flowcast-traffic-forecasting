"""Compare a saved run's outputs with the current ones, and write reports/reproducibility.md.

Usage: python scripts/compare_runs.py <folder holding the earlier run's files>
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
# Elapsed-time columns legitimately vary between runs, so they aren't compared.
TIMING = ("infer_ms", "search_s", "fit_s", "seconds")
BOARDS = ["volume", "travel_time", "speed", "congestion", "accident"]


def numeric_differences(before: pd.DataFrame, after: pd.DataFrame) -> tuple:
    """Largest absolute difference across shared numeric columns that aren't timings."""
    columns = [c for c in before.columns if c in after.columns and pd.api.types.is_numeric_dtype(before[c]) and not any(t in c for t in TIMING)]
    differences = {c: float(np.nanmax(np.abs(before[c].to_numpy(float) - after[c].to_numpy(float)))) for c in columns if not before[c].isna().all()}
    worst = max(differences, key=differences.get) if differences else "-"
    return len(differences), worst, differences.get(worst, 0.0)


def main(earlier: Path) -> None:
    lines = ["| Output | Compared | Largest difference | Column |", "|---|---:|---:|---|"]
    for name in BOARDS:
        before, after = pd.read_csv(earlier / f"scoreboard_{name}.csv"), pd.read_csv(ROOT / "reports" / f"scoreboard_{name}.csv")
        if list(before["model"]) != list(after["model"]):
            lines.append(f"| Scoreboard: {name} | Different models listed | - | - |")
            continue
        count, worst, value = numeric_differences(before, after)
        lines.append(f"| Scoreboard: {name} | {count} columns | {value:.6f} | {worst} |")
    count, worst, value = numeric_differences(pd.read_csv(earlier / "metrics_by_horizon.csv"), pd.read_csv(ROOT / "reports" / "metrics_by_horizon.csv"))
    lines.append(f"| Metrics by horizon | {count} columns | {value:.6f} | {worst} |")

    before, after = pd.read_parquet(earlier / "predictions.parquet"), pd.read_parquet(ROOT / "data" / "processed" / "predictions.parquet")
    keys = ["road_id", "issue_ts", "horizon"]
    before, after = before.sort_values(keys).reset_index(drop=True), after.sort_values(keys).reset_index(drop=True)
    same_rows = len(before) == len(after)
    lines.append(f"| Forecast rows | {len(after):,} rows | {'Same' if same_rows else 'Different'} row count | - |")
    if same_rows:
        for column in ["volume_pred", "speed_pred", "travel_time_pred", "accident_prob"]:
            lines.append(f"| Forecasts: {column} | {len(after):,} rows | {float((before[column] - after[column]).abs().max()):.6f} | - |")
        lines.append(f"| Forecasts: congestion class | {len(after):,} rows | {int((before['congestion_pred'] != after['congestion_pred']).sum())} rows differ | - |")
        lines.append(f"| Forecasts: input hash | {len(after):,} rows | {int((before['input_hash'] != after['input_hash']).sum())} rows differ | - |")

    earlier_manifest = json.loads((earlier / "dataset_manifest.json").read_text(encoding="utf-8"))
    current_manifest = json.loads((ROOT / "data" / "processed" / "dataset_manifest.json").read_text(encoding="utf-8"))
    same_data = earlier_manifest["sha256"] == current_manifest["sha256"]
    registry_before = json.loads((earlier / "registry.json").read_text(encoding="utf-8"))
    registry_after = json.loads((ROOT / "models" / "registry.json").read_text(encoding="utf-8"))
    winners = {k: v["model"] for k, v in registry_before["targets"].items()} == {k: v["model"] for k, v in registry_after["targets"].items()}
    text = f"""# Reproducibility check

Generated by `scripts/compare_runs.py`. All generated data and models were deleted, then `python -m src.pipeline all` rebuilt them from the raw files. This compares that rebuild with the earlier run. Both used the same machine and a CUDA build of PyTorch. Elapsed times aren't compared.

- **Dataset hash:** {"identical" if same_data else "DIFFERENT"} (`{current_manifest["sha256"][:12]}`, {current_manifest["rows"]:,} rows)
- **Winning models:** {"identical" if winners else "DIFFERENT"}
- **Deep model in service:** {registry_after["deep"]["model"]} (earlier run: {registry_before["deep"]["model"]})

{chr(10).join(lines)}
"""
    path = ROOT / "reports" / "reproducibility.md"
    path.write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    main(Path(sys.argv[1]))
